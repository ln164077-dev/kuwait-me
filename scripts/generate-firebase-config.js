#!/usr/bin/env node
/**
 * يبني assets/js/firebase-config.js من متغيرات البيئة (أسرار).
 * يُشغَّل تلقائياً على Netlify قبل النشر، ومحلياً عبر: npm run build
 */
'use strict';

const fs = require('fs');
const path = require('path');

const OUT_FILE = path.join(__dirname, '..', 'assets', 'js', 'firebase-config.js');

const firebaseKeys = {
  apiKey: 'FIREBASE_API_KEY',
  authDomain: 'FIREBASE_AUTH_DOMAIN',
  databaseURL: 'FIREBASE_DATABASE_URL',
  projectId: 'FIREBASE_PROJECT_ID',
  storageBucket: 'FIREBASE_STORAGE_BUCKET',
  messagingSenderId: 'FIREBASE_MESSAGING_SENDER_ID',
  appId: 'FIREBASE_APP_ID',
  measurementId: 'FIREBASE_MEASUREMENT_ID'
};

const optionalEnv = new Set(['FIREBASE_DATABASE_URL', 'FIREBASE_MEASUREMENT_ID']);

function readEnv(name) {
  const value = process.env[name];
  return typeof value === 'string' ? value.trim() : '';
}

const missing = [];
const firebaseConfig = {};

for (const [key, envName] of Object.entries(firebaseKeys)) {
  const value = readEnv(envName);
  if (!value && !optionalEnv.has(envName)) missing.push(envName);
  if (value) firebaseConfig[key] = value;
}

const panelEmail = readEnv('PANEL_EMAIL');
const panelPassword = readEnv('PANEL_PASSWORD');
if (!panelEmail) missing.push('PANEL_EMAIL');
if (!panelPassword) missing.push('PANEL_PASSWORD');

if (missing.length) {
  console.error('[firebase-config] متغيرات بيئة مفقودة: ' + missing.join(', '));
  process.exit(1);
}

const content = `/* ملف مُولَّد تلقائياً من متغيرات البيئة — لا تعدّله ولا ترفعه إلى المستودع. */
/* Generated by scripts/generate-firebase-config.js — do not edit or commit. */
window.__FIREBASE_CONFIG__ = ${JSON.stringify(firebaseConfig, null, 2)};

window.__PANEL_CREDS__ = {
  email: ${JSON.stringify(panelEmail)},
  password: ${JSON.stringify(panelPassword)}
};
`;

fs.writeFileSync(OUT_FILE, content, 'utf8');
console.log('[firebase-config] تم إنشاء ' + path.relative(path.join(__dirname, '..'), OUT_FILE));
